def _normalize_s3_endpoint(value):
    """Strip whitespace and auto-prefix scheme so boto3 doesn't reject bare hosts."""
    value = (value or "").strip()
    if not value:
        return ""
    if "://" not in value:
        value = f"https://{value}"
    return value


